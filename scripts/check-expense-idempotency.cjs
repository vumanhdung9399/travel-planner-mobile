const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/services/expense-idempotency.ts'), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const result = { exports: {} };
new Function('exports', 'module', compiled)(result.exports, result);
const { expenseMutationData } = result.exports;
let generated = 0;
const createId = () => 'submit-' + ++generated;
const input = { title: 'Lunch', participants: ['a', 'b', 'c'].map(userId => ({ userId })) };
const first = expenseMutationData(input, createId);
const retried = expenseMutationData(JSON.stringify(first), createId);
assert.deepEqual(retried, first);
assert.equal(generated, 1);
assert.equal(retried.participants.length, 3);
assert.equal('0' in retried, false);
assert.deepEqual(expenseMutationData(retried, createId), first);
assert.equal(generated, 1);
assert.notEqual(expenseMutationData(input, createId).clientMutationId, first.clientMutationId);
assert.equal('clientMutationId' in input, false);
console.log('Expense JSON retry, offline replay and separate submissions: passed');
